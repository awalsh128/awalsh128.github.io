#!/usr/bin/env python3

"""Sync the homepage project list with a hardcoded list of GitHub repositories.

Each repository in REPOS is validated through the GitHub CLI (`gh`): it must exist
and be reachable, otherwise the script fails. The bullet list between the projects
markers in content/_index.md is then rewritten inside a collapsed <details> block,
with the "Projects" heading as its toggle and a heading per group of REPOS.
Each bullet starts with the project's icon (the `project-icon` shortcode), links
the repository name to GitHub, and ends with the first sentence of its
description.

Icons are downloaded by project_logos.py: each repository's README logo, or the
file named in LOGO_OVERRIDES.

Exits non-zero when `gh` is missing or a repository is not found, so callers such
as the pre-commit hook can decide whether that should block.
"""

from pathlib import Path
import argparse
import json
import subprocess
import sys

from github_api import gh_api
from generated_markdown import first_sentence, replace_between
from project_logos import sync_logos

ROOT_DIR = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT_DIR / "content" / "_index.md"
# Projects shown on the homepage, grouped by type. Groups and the repositories in them render in this order, each
# group under its own heading inside the collapsed block.
REPOS = {
    "GitHub Actions and CI/CD": [
        "awalsh128/cache-apt-pkgs-action",
        "awalsh128/npm-publish-strict",
        "awalsh128/semantic-release-sentinel-app",
    ],
    "Editor extensions": [
        "awalsh128/vscode-keep-sorted",
        "awalsh128/vscode-regex-explain",
    ],
    "AI agents and templates": [
        "awalsh128/skills",
        "awalsh128/gh-dev-powerpack",
    ],
    "Libraries": [
        "awalsh128/winston-host-adapters",
        "awalsh128/ts-apt",
        "awalsh128/fluentcpp",
        "awalsh128/PcapngFile",
    ],
}
# Repository name -> path of the logo file inside that repository, used instead of the README's first image.
LOGO_OVERRIDES = {
    "fluentcpp": "assets/artwork/fluentcpp-initial-sm.png",
}


START_MARKER = "<!-- projects:start (generated by scripts/update_projects.py) -->"
END_MARKER = "<!-- projects:end -->"


def fetch_repos(slugs: list[str]) -> list[dict]:
  """Look up each repository, raising LookupError listing every one that does not exist."""
  repos, missing = [], []
  for slug in slugs:
    try:
      data = json.loads(gh_api(f"repos/{slug}"))
    except subprocess.CalledProcessError as error:
      missing.append(f"{slug} ({error.stderr.decode().strip() or 'lookup failed'})")
      continue
    repos.append(
        {
            "name": data["name"],
            "nameWithOwner": data["full_name"],
            "description": data["description"],
            "url": data["html_url"],
        }
    )
  if missing:
    raise LookupError("repositories not found: " + "; ".join(missing))
  return repos


def render_bullet(repo: dict) -> str:
  line = f"- {{{{< project-icon \"{repo['name']}\" >}}}} [**{repo['name']}**]({repo['url']})"
  description = first_sentence(repo.get("description"))
  return f"{line}: {description}" if description else line


def render(groups: dict[str, list[dict]]) -> str:
  sections = []
  for group, repos in groups.items():
    bullets = "\n".join(render_bullet(repo) for repo in repos)
    sections.append(f"### {group}\n\n{bullets}")
  body = "\n\n".join(sections)
  # The section heading is the toggle, so the list collapses under it (styled in assets/css/custom/20-home.css).
  summary = '<summary><h2 id="projects">My Open Source Projects</h2></summary>'
  return f"<details>\n{summary}\n\n{body}\n\n</details>"


def main() -> int:
  parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
  parser.add_argument("--output", default=str(DEFAULT_OUTPUT), help="file to update, or - to print the list")
  args = parser.parse_args()

  try:
    slugs = [slug for group in REPOS.values() for slug in group]
    fetched = dict(zip(slugs, fetch_repos(slugs)))
  except FileNotFoundError:
    print("update_projects: gh CLI not found", file=sys.stderr)
    return 1
  except (LookupError, KeyError, json.JSONDecodeError) as error:
    print(f"update_projects: {error}", file=sys.stderr)
    return 1

  groups = {group: [fetched[slug] for slug in group_slugs] for group, group_slugs in REPOS.items()}
  projects = render(groups)
  if args.output == "-":
    print(projects)
    return 0

  sync_logos(list(fetched.values()), LOGO_OVERRIDES)

  path = Path(args.output)
  content = path.read_text()
  try:
    updated = replace_between(content, START_MARKER, END_MARKER, projects)
  except ValueError as error:
    print(f"update_projects: {error}", file=sys.stderr)
    return 1
  if updated != content:
    path.write_text(updated)
    print(f"update_projects: updated {path.relative_to(ROOT_DIR)}", file=sys.stderr)
  return 0


if __name__ == "__main__":
  sys.exit(main())
